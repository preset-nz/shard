//! music, and a few hand-written.
//!
//! How the source became this table, once, by a script (not kept):
//! - only `prog_min` and `prog_modal` (the minor and modal lists) were read;
//! - each chord was reduced to its root and triad (extensions, sevenths and
//!   sus chords dropped), slash chords skipped;
//! - a progression stays only when every chord's root and quality is
//!   diatonic to one of `Mode::ALL`, and only with eight chords or fewer;
//! - those reading as the same degrees in the same mode were merged, their
//!   tags joined;
//! - mood tags lower-cased; "New" and "Cadence" dropped, being no feel.
//!
//! Names are written from the degrees in the home mode, accidentals against
//! the major scale (`i-bVI-bVII`), so one name means one sound whatever mode
//! the list came from. Entries whose `source` is None are Shard's own, and
//! come first, since a model leans towards the start of a list:
//! EBM staples (one chord, i-bII, i-bVI) and the harmonic minor, phrygian
//! dominant and locrian moves the source has few of.

